import { chmod, lstat, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { writeDurable } from "../durable-write.ts";
import { resolvedMain } from "../link.ts";
import { stateDir } from "../paths.ts";
import { baseChildEnv } from "../usage-refresh.ts";

/**
 * The machine's one Codex home (docs/codex.md, "Where the login lives"; DESIGN.md, Daemon, "Codex login"): every Codex
 * process Séance runs gets this `CODEX_HOME`, so one sign-in serves them all and Codex's own `auth.lock` serializes a
 * refresh between them. The daemon writes `config.toml` here and nothing else; `auth.json` is Codex's alone, and nothing
 * in Séance opens, reads, copies or links it.
 */

/** 0700, the daemon's own: the home's parent, where phase 3's `remote.json` goes beside it. */
export function codexDir(stateDirectory: string = stateDir()): string {
  return join(stateDirectory, "codex");
}

export function codexHome(stateDirectory: string = stateDir()): string {
  return join(codexDir(stateDirectory), "home");
}

/** Resolved through `PATH` at each use, as `spawn.ts` resolves `claude`; `SEANCE_CODEX_BIN` is the tests' stub. */
export function codexBin(): string {
  return process.env["SEANCE_CODEX_BIN"] ?? "codex";
}

/**
 * A Codex child's whole environment, never the daemon's: the base a Claude-adjacent child gets (`HOME`, `PATH`, `USER`,
 * `LOGNAME`) plus `CODEX_HOME`. Built bare, so a service-delivered credential cannot reach it and the owner's own
 * `CODEX_HOME` (their `~/.codex`) is never inherited.
 */
export function codexEnv(home: string, userHome: string): Readonly<Record<string, string>> {
  return { ...baseChildEnv(userHome), CODEX_HOME: home };
}

/**
 * Whether the owner's own Codex home holds a sign-in: `~/.codex/auth.json` under the children's `HOME` (`codexEnv`'s
 * `userHome`), never `CODEX_HOME`. Asked only while Séance's home is signed out, to tell a plain `codex login` from no
 * sign-in at all. `lstat` reads the directory entry alone: the file is never opened, read, copied or linked.
 */
export async function ownerCodexAuth(userHome: string): Promise<boolean> {
  return (await lstat(join(userHome, ".codex", "auth.json")).catch(() => null)) !== null;
}

/** How Codex starts Séance's MCP server: bun by its `PATH` name and this checkout's entry point. */
export interface McpLaunch {
  readonly command: string;
  readonly args: readonly string[];
}

/**
 * The whole file, regenerated rather than edited. JSON's string escape is a valid TOML basic string, so a path with a
 * quote or a backslash in it cannot break out of its value.
 */
export function renderCodexConfig(mcp: McpLaunch | null): string {
  const lines = [
    "# Generated by seanced at each start; edits are overwritten (docs/codex.md).",
    // Codex reads the file store from config at sign-in and at every later read: set before `seance codex login` runs.
    'cli_auth_credentials_store = "file"',
    "check_for_update_on_startup = false",
    'project_doc_fallback_filenames = ["CLAUDE.md"]',
    "project_doc_max_bytes = 262144",
  ];
  if (mcp !== null) {
    lines.push(
      "",
      "[mcp_servers.seance]",
      `command = ${JSON.stringify(mcp.command)}`,
      `args = [${mcp.args.map((arg) => JSON.stringify(arg)).join(", ")}]`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Bun by its `PATH` name only. `resolvedBun` falls back to `process.execPath` for records that need some path, but
 * this one outlives the process and is rewritten at every start, so no entry beats one that dangles after an upgrade.
 */
export async function mcpLaunch(bunOnPath: string | null = Bun.which("bun")): Promise<McpLaunch | null> {
  if (bunOnPath === null) return null;
  return { command: bunOnPath, args: [await resolvedMain(), "mcp"] };
}

export interface PreparedHome {
  readonly home: string;
  /** False when bun was not on `PATH`: the file was written without the Séance MCP server. */
  readonly mcp: boolean;
}

/**
 * Makes the home and writes `config.toml`. Both directories are held to 0700 even when they already exist (`mkdir`'s
 * mode applies only to a directory it creates); the file is 0600, published by rename.
 */
export async function prepareCodexHome(
  stateDirectory: string = stateDir(),
  launch?: McpLaunch | null,
): Promise<PreparedHome> {
  const dir = codexDir(stateDirectory);
  const home = codexHome(stateDirectory);
  await mkdir(home, { recursive: true, mode: 0o700 });
  await chmod(dir, 0o700);
  await chmod(home, 0o700);
  const mcp = launch === undefined ? await mcpLaunch() : launch;
  await writeDurable(join(home, "config.toml"), renderCodexConfig(mcp), 0o600);
  return { home, mcp: mcp !== null };
}
