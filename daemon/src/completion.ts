// `seance completion`: the zsh script, generated from `COMMAND_SPECS` like the help, so a command, verb or flag added
// there completes with no second edit. Loaded by `main.ts` on demand; `repos` runs on every Tab after `spawn`, so it
// reads the state file and nothing else.
import {
  CLI_NAME,
  COMMAND_SPECS,
  COMMANDS,
  usageLine,
  type CommandSpec,
  type FlagSpec,
  type VerbSpec,
} from "./commands.ts";

/** A zsh single-quoted word. */
function sq(text: string): string {
  return `'${text.replaceAll("'", `'\\''`)}'`;
}

/** An `_arguments` explanation or message: brackets and colons end the field they sit in. */
function field(text: string): string {
  return text.replaceAll("\\", "\\\\").replaceAll("[", "\\[").replaceAll("]", "\\]").replaceAll(":", "\\:");
}

function describeItem(name: string, summary: string): string {
  return sq(`${name.replaceAll(":", "\\:")}:${summary}`);
}

function flagSpec(spec: FlagSpec): string {
  const help = `[${field(spec.help)}]`;
  const value =
    spec.value === undefined
      ? ""
      : `:${field(spec.value)}:${spec.choices === undefined ? "" : `(${spec.choices.join(" ")})`}`;
  if (spec.alias !== undefined) {
    // `(-p --prompt)` excludes the pair from each other; the brace pair zsh expands into two specs.
    const exclusion = spec.repeatable === true ? "*" : sq(`(${spec.flag} ${spec.alias})`);
    return `${exclusion}{${spec.flag},${spec.alias}}${sq(`${help}${value}`)}`;
  }
  return sq(`${spec.repeatable === true ? "*" : ""}${spec.flag}${help}${value}`);
}

const ARG_ACTIONS = {
  repo: "1:repo:_seance_repos",
  command: "1:command:_seance_commands",
  dir: "1:dir:_directories",
} as const;

function argumentsCall(flags: readonly FlagSpec[], arg: CommandSpec["arg"], indent: string): string {
  const specs = [...flags.map(flagSpec), ...(arg === undefined ? [] : [sq(ARG_ACTIONS[arg])])];
  if (specs.length === 0) return `${indent}_message 'no more arguments'`;
  return `${indent}_arguments -s \\\n${specs.map((spec) => `${indent}  ${spec}`).join(" \\\n")}`;
}

function verbsBlock(name: string, verbs: Readonly<Record<string, VerbSpec>>): string {
  const offered = Object.entries(verbs).filter(([, verb]) => verb.internal !== true);
  const withFlags = offered.filter(([, verb]) => (verb.flags ?? []).length > 0);
  const lines = [
    `      if (( CURRENT == 2 )); then`,
    `        local -a verbs=(${offered.map(([verb, spec]) => describeItem(verb, spec.summary)).join(" ")})`,
    `        _describe -t verbs ${sq(`${CLI_NAME} ${name} verb`)} verbs`,
    `        return`,
    `      fi`,
  ];
  if (withFlags.length === 0) return lines.join("\n");
  lines.push(`      shift words`, `      (( CURRENT-- ))`, `      case $words[1] in`);
  for (const [verb, spec] of withFlags) {
    lines.push(`        (${verb})`, argumentsCall(spec.flags ?? [], undefined, "          "), `          ;;`);
  }
  lines.push(`      esac`);
  return lines.join("\n");
}

function commandCase(name: string, spec: CommandSpec): string {
  const body =
    spec.verbs === undefined ? argumentsCall(spec.flags ?? [], spec.arg, "      ") : verbsBlock(name, spec.verbs);
  return `    (${name})\n${body}\n      ;;`;
}

/** The completion script: `eval "$(seance completion zsh)"` after compinit, or saved as `_seance` on `$fpath`. */
export function zshCompletion(): string {
  const offered = COMMANDS.filter((name) => COMMAND_SPECS[name].internal !== true);
  return `#compdef ${CLI_NAME}
# Generated by \`${CLI_NAME} completion zsh\` from the CLI's command table (daemon/src/commands.ts); regenerate, never edit.

_seance_commands() {
  local -a commands=(
${offered.map((name) => `    ${describeItem(name, COMMAND_SPECS[name].summary)}`).join("\n")}
  )
  _describe -t commands ${sq(`${CLI_NAME} command`)} commands
}

_seance_repos() {
  local -a repos=(\${(f)"$(${CLI_NAME} completion repos 2>/dev/null)"})
  _describe -t repos 'repo' repos
}

_seance() {
  if (( CURRENT == 2 )); then
    _seance_commands
    return
  fi
  local command=$words[2]
  shift words
  (( CURRENT-- ))
  case $command in
${offered.map((name) => commandCase(name, COMMAND_SPECS[name])).join("\n")}
  esac
}

if [[ $zsh_eval_context[-1] == loadautofunc ]]; then
  _seance "$@"
else
  compdef _seance ${CLI_NAME}
fi
`;
}

/** This machine's scanned repo names, for `spawn`'s first argument. Silent on any failure: a Tab must never print. */
async function repoNames(): Promise<readonly string[]> {
  try {
    const { readState } = await import("./state.ts");
    const state = await readState();
    return [...new Set((state?.repos ?? []).map((repo) => repo.name))].toSorted();
  } catch {
    return [];
  }
}

export async function cmdCompletion(rest: readonly string[]): Promise<void> {
  const [shell, ...extra] = rest;
  if (extra.length > 0) throw new Error(usageLine("completion"));
  if (shell === "zsh") {
    process.stdout.write(zshCompletion());
    return;
  }
  if (shell === "repos") {
    for (const name of await repoNames()) console.log(name);
    return;
  }
  throw new Error(usageLine("completion"));
}
